#!/usr/bin/env node
// Writes the encodeQR reference grids for TestEncoderTest (src/test/resources/encoder-fixtures.txt).
// Usage (node >= 22): node --experimental-strip-types tools/js-dump/encoder-fixtures.mjs <qr-paulmillr-dir> > out.txt
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

if (process.argv.length < 3) {
  console.error('usage: encoder-fixtures.mjs <qr-paulmillr-dir>');
  process.exit(1);
}
const { encodeQR } = await import(pathToFileURL(join(resolve(process.argv[2]), 'src', 'index.ts')).href);
const cases = [
  ['HELLO WORLD', { version: 1, ecc: 'medium', mask: 0, border: 4 }],
  ['HELLO WORLD', {}],
  ['hello, wörld', { version: 3, ecc: 'low', mask: 5, border: 2 }],
  ['0123456789012345678901234567890123456789', { version: 7, ecc: 'high', encoding: 'numeric', border: 4 }],
  ['vita nuova — 🌒🌓', { version: 12, ecc: 'quartile', border: 1 }],
  ['DAMAGE TEST 123', { version: 2, ecc: 'high', border: 4 }],
];
const out = [
  '# encodeQR(text, "raw", opts) from paulmillr/qr v0.7.2; generated by scratchpad harness/encoder-fixtures.ts',
  '# per case: "case <json text>\\t<json opts>", then one row per line, 1 = dark',
];
for (const [text, opts] of cases) {
  out.push(`case ${JSON.stringify(text)}\t${JSON.stringify(opts)}`);
  for (const row of encodeQR(text, 'raw', opts)) out.push(row.map((b) => (b ? '1' : '0')).join(''));
}
console.log(out.join('\n'));
